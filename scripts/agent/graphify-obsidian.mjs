#!/usr/bin/env node
/**
 * graphify-obsidian — render the bizOS repository graph into the owner's real
 * Obsidian vault (~/second-brain), as one note per real entity with wikilinks
 * between them, not a markdown dump.
 *
 * Rebuilt 2026-09-08. A prior version of this file (and its destination,
 * docs/vault/) was deliberately removed 2026-08-30 -- see
 * docs/journal/2026-08-30-resolve-outstanding-open-items-branch-triage-main-sync-hosti.md,
 * Decision 5. The objections, and how this version answers each:
 *
 *   1. "A parallel, hand-editable Obsidian mirror... a fourth, undocumented
 *      artifact with drift risk." -- This is not a fourth artifact. It has no
 *      data of its own: every note is a rendering of .agent/graph.json (the
 *      one already-documented artifact `pnpm graph` produces), regenerated by
 *      this script in the same run as `pnpm graph` (see ~/bin/graphify-obsidian).
 *      It cannot drift from the graph because it has nothing to drift with --
 *      it IS the graph, laid out for Obsidian. Documented here and in
 *      docs/multi-agent-protocol.md rather than left implicit.
 *   2. "Referencing a fictional six-person agent roster." -- Every note below
 *      is built from a field already present in .agent/graph.json: workspace
 *      names/paths/deps from discoverWorkspaces(), owners from CODEOWNERS,
 *      decisions from docs/decisions/*.md. Nothing here is invented. If a
 *      fact isn't in the graph, it isn't in a note.
 *   3. "Tied to an external, non-bizOS path" (HarnessAgents/hive/...). --
 *      Nothing here references anything outside bizOS's own graph data. The
 *      destination vault is the owner's own real vault, not a new isolated
 *      path nobody opens.
 *
 * Every note carries a generated/do-not-hand-edit marker -- that marker
 * failing to exist was not itself the original sin, but it's cheap insurance
 * against this becoming editable-and-drifting a second time.
 *
 * Usage: node scripts/agent/graphify-obsidian.mjs [--vault <path>]
 * Reads .agent/graph.json (run `pnpm graph` first -- this script does not
 * regenerate it). Writes only inside <vault>/Generated/bizOS/ -- touches
 * nothing else in the vault.
 */
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const repositoryRoot = process.cwd();
const graphPath = join(repositoryRoot, ".agent", "graph.json");

const vaultArgIndex = process.argv.indexOf("--vault");
const vaultRoot =
  vaultArgIndex !== -1 ? process.argv[vaultArgIndex + 1] : join(homedir(), "second-brain");
const outDir = join(vaultRoot, "Generated", "bizOS");

if (!existsSync(vaultRoot)) {
  console.error(`ABORT: vault root does not exist: ${vaultRoot}`);
  process.exit(1);
}
// Refuse to write anywhere in the vault except our own namespaced folder --
// this is the actual enforcement of "never touch hand-written notes", not
// just a comment.
if (!outDir.startsWith(join(vaultRoot, "Generated") + "/")) {
  console.error(`ABORT: refusing to write outside Generated/bizOS/: ${outDir}`);
  process.exit(1);
}

const graph = JSON.parse(await readFile(graphPath, "utf8"));
const nowIso = new Date().toISOString();

// Decision slugs key off the full filename stem, not the bare 4-digit id --
// docs/decisions/ has a known, pre-existing duplicate-numbering issue (two
// 0021s, two 0022s; see docs/decisions/README.md and the 2026-08-30 journal
// entry). Keying on id alone would silently collide two different ADRs onto
// one filename and drop one -- the stem is unique because the files
// themselves are.
function decisionStem(path) {
  return path.replace(/^.*\//, "").replace(/\.md$/, "");
}

const slug = {
  workspace: (name) => `bizOS - ${name.replace(/\//g, "-")}`,
  decision: (path) => `bizOS - ADR-${decisionStem(path)}`,
  owner: (name) => `bizOS - owner ${name.replace(/[@/]/g, "")}`,
};

const GENERATED_NOTICE = (source) => `> [!warning] Generated note -- do not hand-edit
> Rendered from \`${source}\` by \`scripts/agent/graphify-obsidian.mjs\`, in the same run as
> \`pnpm graph\`. Edits made here are overwritten on the next regeneration. To change this
> content, edit the real source in the bizOS repo and regenerate.

`;

function frontmatter(fields) {
  const lines = ["---"];
  for (const [key, value] of Object.entries(fields)) {
    if (Array.isArray(value)) {
      lines.push(`${key}:`);
      for (const v of value) lines.push(`  - ${v}`);
    } else {
      lines.push(`${key}: ${JSON.stringify(value)}`);
    }
  }
  lines.push("---", "");
  return lines.join("\n");
}

function wikilink(title) {
  return `[[${title}]]`;
}

// -- derive ADR -> workspaces from workspaces[].governingDocs, since the
// graph stores that relationship on the workspace side only. Keyed by the
// full doc path (see decisionStem's comment above) so the two known
// duplicate-numbered ADR pairs don't collide here either.
const adrToWorkspaces = new Map();
for (const ws of graph.workspaces) {
  for (const doc of ws.governingDocs ?? []) {
    if (!doc.match(/^docs\/decisions\//)) continue;
    if (!adrToWorkspaces.has(doc)) adrToWorkspaces.set(doc, []);
    adrToWorkspaces.get(doc).push(ws.name);
  }
}

// -- derive owner -> workspaces from workspaces[].owners.
const ownerToWorkspaces = new Map();
for (const ws of graph.workspaces) {
  for (const owner of ws.owners ?? []) {
    if (!ownerToWorkspaces.has(owner)) ownerToWorkspaces.set(owner, []);
    ownerToWorkspaces.get(owner).push(ws.name);
  }
}

async function main() {
  await mkdir(outDir, { recursive: true });
  // Clean regeneration: remove prior generated notes first so a workspace or
  // ADR that no longer exists doesn't leave a dangling note behind. Safe --
  // outDir is checked above to be inside Generated/bizOS/ only.
  for (const entry of await readdir(outDir).catch(() => [])) {
    if (entry.endsWith(".md")) await rm(join(outDir, entry));
  }

  const workspaceNotes = [];
  for (const ws of graph.workspaces) {
    const title = slug.workspace(ws.name);
    const body =
      GENERATED_NOTICE(".agent/graph.json") +
      `# ${ws.name}\n\n` +
      `**Type:** ${ws.type}\n` +
      `**Path:** \`${ws.path}\`\n` +
      (ws.description ? `**Description:** ${ws.description}\n` : "") +
      `\n## Owners\n` +
      (ws.owners?.length
        ? ws.owners.map((o) => `- ${wikilink(slug.owner(o))}`).join("\n")
        : "_none recorded in CODEOWNERS_") +
      `\n\n## Depends on\n` +
      (ws.dependsOn?.length
        ? ws.dependsOn.map((d) => `- ${wikilink(slug.workspace(d))}`).join("\n")
        : "_none -- layer 0_") +
      `\n\n## Depended on by\n` +
      (ws.dependedOnBy?.length
        ? ws.dependedOnBy.map((d) => `- ${wikilink(slug.workspace(d))}`).join("\n")
        : "_nothing else in this workspace depends on it_") +
      `\n\n## Governing decisions\n` +
      ((ws.governingDocs ?? []).filter((d) => d.match(/docs\/decisions\//)).length
        ? (ws.governingDocs ?? [])
            .filter((d) => d.match(/^docs\/decisions\//))
            .map((d) => `- ${wikilink(slug.decision(d))}`)
            .join("\n")
        : "_none_") +
      `\n\n## Scripts\n` +
      (ws.scripts?.length ? ws.scripts.map((s) => `- \`${s}\``).join("\n") : "_none_") +
      `\n`;
    const fm = frontmatter({
      title: ws.name,
      type: "workspace",
      tags: ["bizos", "workspace", "generated"],
      generated: true,
      source: ".agent/graph.json",
      generated_at: nowIso,
      status: "evergreen",
    });
    await writeFile(join(outDir, `${title}.md`), fm + body, "utf8");
    workspaceNotes.push({ title, name: ws.name, type: ws.type });
  }

  const decisionNotes = [];
  for (const adr of graph.decisions) {
    if (!adr.path) continue;
    const title = slug.decision(adr.path);
    const affected = adrToWorkspaces.get(adr.path) ?? [];
    const body =
      GENERATED_NOTICE(".agent/graph.json") +
      `# ${adr.title ?? `ADR-${adr.id}`}\n\n` +
      `**Status:** ${adr.status}\n` +
      (adr.date ? `**Date:** ${adr.date}\n` : "") +
      `**Source file (bizOS repo):** \`${adr.path}\` -- this note is an index entry, not a copy;\n` +
      `read the real decision text at that path.\n\n` +
      `## Affects\n` +
      (affected.length
        ? affected.map((w) => `- ${wikilink(slug.workspace(w))}`).join("\n")
        : "_no workspace in the graph references this decision by path_") +
      `\n`;
    const fm = frontmatter({
      title: adr.title ?? `ADR-${adr.id}`,
      type: "decision",
      tags: ["bizos", "adr", "generated"],
      generated: true,
      status: adr.status,
      ...(adr.date ? { date: adr.date } : {}),
      source: ".agent/graph.json",
      generated_at: nowIso,
    });
    await writeFile(join(outDir, `${title}.md`), fm + body, "utf8");
    decisionNotes.push({ title, id: adr.id, status: adr.status });
  }

  const ownerNotes = [];
  for (const [owner, workspaces] of ownerToWorkspaces) {
    const title = slug.owner(owner);
    const body =
      GENERATED_NOTICE(".agent/graph.json") +
      `# ${owner}\n\n` +
      `## Owns (per CODEOWNERS)\n` +
      workspaces.map((w) => `- ${wikilink(slug.workspace(w))}`).join("\n") +
      `\n`;
    const fm = frontmatter({
      title: owner,
      type: "person",
      tags: ["bizos", "owner", "generated"],
      generated: true,
      source: ".agent/graph.json",
      generated_at: nowIso,
    });
    await writeFile(join(outDir, `${title}.md`), fm + body, "utf8");
    ownerNotes.push({ title, owner });
  }

  // -- topic MOCs
  const workspacesMocTitle = "bizOS - Workspaces MOC";
  await writeFile(
    join(outDir, `${workspacesMocTitle}.md`),
    frontmatter({
      type: "moc",
      tags: ["moc", "bizos", "generated"],
      generated: true,
      generated_at: nowIso,
    }) +
      GENERATED_NOTICE(".agent/graph.json") +
      `# bizOS Workspaces\n\n` +
      `${graph.summary.appCount} app(s), ${graph.summary.packageCount} package(s), ` +
      `${graph.summary.edgeCount} internal dependency edge(s).\n\n` +
      `## Apps\n` +
      workspaceNotes
        .filter((w) => w.type === "app")
        .map((w) => `- ${wikilink(w.title)}`)
        .join("\n") +
      `\n\n## Packages\n` +
      workspaceNotes
        .filter((w) => w.type !== "app")
        .map((w) => `- ${wikilink(w.title)}`)
        .join("\n") +
      `\n`,
    "utf8",
  );

  const decisionsMocTitle = "bizOS - Decisions MOC";
  const byStatus = new Map();
  for (const d of decisionNotes) {
    if (!byStatus.has(d.status)) byStatus.set(d.status, []);
    byStatus.get(d.status).push(d);
  }
  await writeFile(
    join(outDir, `${decisionsMocTitle}.md`),
    frontmatter({
      type: "moc",
      tags: ["moc", "bizos", "generated"],
      generated: true,
      generated_at: nowIso,
    }) +
      GENERATED_NOTICE(".agent/graph.json") +
      `# bizOS Decisions (ADRs)\n\n${decisionNotes.length} recorded.\n\n` +
      [...byStatus.entries()]
        .map(
          ([status, ds]) => `## ${status}\n` + ds.map((d) => `- ${wikilink(d.title)}`).join("\n"),
        )
        .join("\n\n") +
      `\n`,
    "utf8",
  );

  const ownersMocTitle = "bizOS - Owners MOC";
  await writeFile(
    join(outDir, `${ownersMocTitle}.md`),
    frontmatter({
      type: "moc",
      tags: ["moc", "bizos", "generated"],
      generated: true,
      generated_at: nowIso,
    }) +
      GENERATED_NOTICE(".agent/graph.json") +
      `# bizOS Owners\n\n` +
      ownerNotes.map((o) => `- ${wikilink(o.title)}`).join("\n") +
      `\n`,
    "utf8",
  );

  // -- home MOC
  await writeFile(
    join(outDir, `bizOS - MOC.md`),
    frontmatter({
      type: "moc",
      tags: ["moc", "bizos", "generated"],
      generated: true,
      generated_at: nowIso,
    }) +
      GENERATED_NOTICE(".agent/graph.json") +
      `# bizOS — Map of Content\n\n` +
      `Generated view of the bizOS repository graph (\`.agent/graph.json\`, built by ` +
      `\`pnpm graph\`). Not a separate source of truth -- if this disagrees with the repo, ` +
      `the repo is right and this is stale; regenerate with \`~/bin/graphify-obsidian\`.\n\n` +
      `**Generated:** ${nowIso}\n` +
      `**Workspaces:** ${graph.summary.workspaceCount} · **Edges:** ${graph.summary.edgeCount} · ` +
      `**Decisions:** ${graph.summary.adrCount}\n\n` +
      `## Sections\n` +
      `- ${wikilink(workspacesMocTitle)}\n` +
      `- ${wikilink(decisionsMocTitle)}\n` +
      `- ${wikilink(ownersMocTitle)}\n`,
    "utf8",
  );

  const totalNotes = workspaceNotes.length + decisionNotes.length + ownerNotes.length + 4;
  console.warn(
    `Obsidian vault rendered: ${totalNotes} notes in ${outDir} ` +
      `(${workspaceNotes.length} workspaces, ${decisionNotes.length} decisions, ` +
      `${ownerNotes.length} owner(s), 4 MOCs).`,
  );
}

await main();
